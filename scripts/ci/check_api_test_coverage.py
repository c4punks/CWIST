#!/usr/bin/env python3
"""Ratchet gate: every public API function must be called by a unit test.

Source of truth for the public surface is docs/api/v4.0-api-baseline.txt
(the "== functions ==" section, regenerated by `make api-baseline`). A
function counts as tested when its name appears in a tests/test_*.c file
that is wired into the Makefile's TEST_TARGETS, so a test that never runs
does not count.

Functions that had no test when this gate was added are listed in
scripts/ci/api-untested-baseline.txt. The gate fails when:

  * a public function is untested and not in that list (new API without a
    test), or
  * a listed function now has a test (remove it from the list, so the list
    only ever shrinks).

v3.9.2 works the list down to empty.

Usage: python3 scripts/ci/check_api_test_coverage.py [repo_root]
       python3 scripts/ci/check_api_test_coverage.py --print-untested [repo_root]
Exit 0 = OK, 1 = gate failure.
"""
from __future__ import annotations
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_test_wiring import parse_test_targets  # noqa: E402

BASELINE = Path("docs/api/v4.0-api-baseline.txt")
UNTESTED = Path("scripts/ci/api-untested-baseline.txt")


def public_functions(text: str) -> set[str]:
    m = re.search(r"^== functions \(\d+\) ==\n(.*?)(?=^==|\Z)", text, re.M | re.S)
    if not m:
        raise ValueError("no '== functions (N) ==' section in the API baseline")
    return {line.strip() for line in m.group(1).splitlines() if line.strip()}


def referenced_names(root: Path) -> set[str]:
    wired = parse_test_targets((root / "Makefile").read_text())
    names: set[str] = set()
    for path in sorted((root / "tests").glob("test_*.c")):
        if path.stem in wired:
            names |= set(re.findall(r"\bcwist_[A-Za-z0-9_]+", path.read_text(errors="replace")))
    return names


def read_list(path: Path) -> set[str]:
    if not path.exists():
        return set()
    out = set()
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.add(line)
    return out


def check(root: Path) -> tuple[list[str], list[str], int, int]:
    funcs = public_functions((root / BASELINE).read_text())
    untested = funcs - referenced_names(root)
    allowed = read_list(root / UNTESTED)
    new_untested = sorted(untested - allowed)
    now_tested = sorted(allowed - untested)
    return new_untested, now_tested, len(funcs), len(untested)


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    root = Path(args[0]) if args else Path(__file__).resolve().parents[2]
    if "--print-untested" in argv:
        funcs = public_functions((root / BASELINE).read_text())
        for name in sorted(funcs - referenced_names(root)):
            print(name)
        return 0
    new_untested, now_tested, total, untested = check(root)
    print(f"API test coverage: {total - untested}/{total} public functions "
          f"called by a wired unit test ({untested} untested).")
    rc = 0
    if new_untested:
        print("\nPublic functions with no unit test (add a test; the list in "
              f"{UNTESTED} is for pre-existing gaps only):")
        for name in new_untested:
            print(f"  {name}")
        rc = 1
    if now_tested:
        print(f"\nNow tested; remove from {UNTESTED}:")
        for name in now_tested:
            print(f"  {name}")
        rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
